function communityFor(slug: string): string {
  const s = slug.toLowerCase();
  for (const [key, text] of COMMUNITY) {
    if (s.includes(key)) return text;
  }
  return "";
}

function item(
  slug: string,
  name: string,
  fields: Omit<Peptide, "slug" | "name" | "productUrl"> & { productUrl?: string },
): Peptide {
  return {
    slug,
    name,
    productUrl: `${AFF}${slug}/?aff=127`,
    inStock: true,
    approvalStatus: "research",
    caution: "Sold for laboratory research only. Not for human or veterinary use.",
    community: communityFor(slug),
    ...fields,
  };
}

